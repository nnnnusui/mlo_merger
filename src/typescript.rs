//! Generates TypeScript types from the same Rust models used by Serde.

use crate::platform::fs;
use specta::ts::{BigIntExportBehavior, ExportConfiguration};
use std::path::Path;

/// Exports report, cache and configuration types without running the asset pipeline.
///
/// JSON serializes file sizes and timestamps as numbers, so their TypeScript
/// representation is `number`, not `bigint`. Consumers must account for precision
/// loss above `Number.MAX_SAFE_INTEGER`; type generation does not validate values.
///
/// ```no_run
/// mlo_merger::typescript::export_types(std::path::Path::new("asset/gen_mlo_merger.ts"))?;
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub fn export_types(output: &Path) -> Result<(), Box<dyn std::error::Error>> {
  if let Some(parent) = output.parent().filter(|parent| !parent.as_os_str().is_empty()) {
    fs::create_dir_all(parent)?;
  }
  // Specta 1 makes every field of an enum variant, and every field that is not an `Option`,
  // required, but `ItemDiff::Removed` leaves out `implied` and `StreamFileOverwrite` `ignore`
  // when they are false, and the removals and modifications of `ItemDiff` and `YmapEntityDiff`
  // leave out `reason` when it is `None`.
  let mut types = sorted_types(&ExportConfiguration::new().bigint(BigIntExportBehavior::Number))?;
  for (required, optional, count) in [
    (
      "{ Removed: { base_index: number; implied: boolean; reason: string | null } }",
      "{ Removed: { base_index: number; implied?: boolean; reason?: string | null } }",
      1,
    ),
    ("; reason: string | null } }", "; reason?: string | null } }", 3),
    ("schema_version: number; ignore: boolean;", "schema_version: number; ignore?: boolean;", 1),
  ] {
    if types.matches(required).count() != count {
      return Err(format!("Generated diff types no longer spell `{required}` as expected").into());
    }
    types = types.replace(required, optional);
  }
  types += crate::app::map::overwrite::YMAP_DIFF_SKIP_TS;
  fs::write(output, types)?;
  Ok(())
}

/// The registered types in TypeScript, ordered by name.
///
/// Specta 1 orders them by a hash of their module and file, so adding or moving a type would
/// reorder the others.
fn sorted_types(conf: &ExportConfiguration) -> Result<String, Box<dyn std::error::Error>> {
  let types = specta::export::TYPES.lock().map_err(|_| "Specta type registry is poisoned")?;
  if let Some(error) = types.1.iter().next() {
    return Err(specta::ts::TsExportError::from(error.clone()).into());
  }
  let mut named = std::collections::BTreeMap::new();
  for (sid, datatype) in &types.0 {
    let datatype = datatype.as_ref().ok_or("Specta type registry holds a placeholder")?;
    if !datatype.export.unwrap_or(true) {
      continue;
    }
    if let Some((other, _)) = named.insert(datatype.name, (sid, datatype))
      && other != sid
    {
      return Err(format!("Duplicate TypeScript type name: {}", datatype.name).into());
    }
  }
  let mut out = "// This file has been generated by Specta. DO NOT EDIT.\n\n".to_string();
  for (_, datatype) in named.into_values() {
    out += &specta::ts::export_datatype(conf, datatype)?;
    out += "\n\n";
  }
  Ok(out)
}

#[cfg(test)]
mod tests {
  use super::*;
  use crate::app::map::stream_conflicts::{StreamConflictReport, StreamFileConflict};
  use std::collections::BTreeMap;

  #[test]
  fn generated_types_are_deterministic_and_cover_serialized_contracts() {
    let path = std::env::temp_dir().join(format!("mlo_typescript_{}.ts", std::process::id()));
    export_types(&path).unwrap();
    let actual = fs::read_to_string(&path).unwrap();
    export_types(&path).unwrap();
    assert_eq!(fs::read_to_string(&path).unwrap(), actual);
    let generated = actual.strip_suffix(crate::app::map::overwrite::YMAP_DIFF_SKIP_TS).unwrap();
    let names = generated
      .lines()
      .filter_map(|line| line.strip_prefix("export type "))
      .map(|line| line.split([' ', '<']).next().unwrap())
      .collect::<Vec<_>>();
    assert!(names.len() > 1);
    assert!(names.is_sorted(), "types are ordered by name");
    for name in [
      "DuplicateReport",
      "MergeMetadata",
      "SourceCacheMetadata",
      "SourceCacheConflictReport",
      "DerivedManifest",
      "VanillaCacheManifest",
      "ArchiveContent",
      "DeployMetadata",
      "MatchingConfig",
      "RTreeIndex",
      "RTreeItem",
      "YmapComparisonDiff",
      "YmapComparisonFile",
      "YbnComparisonDiff",
      "YbnDiffFields",
      "YbnPolygonsDiff",
      "YmapPropagatedDiff",
      "YmapPropagationOrigin",
      "GenerationIndex",
      "YmapGenerationIndex",
      "YbnGenerationIndex",
      "YbnCandidates",
      "YbnCandidate",
      "DlcActivity",
      "YmapImplied",
      "LeftBehind",
      "MergeReportIndex",
      "YmapMergeReport",
      "GenerationUnit",
      "VanillaYmapDiff",
      "VanillaYmapVersion",
      "VanillaYmapVersionIndex",
      "YmapDiffFields",
      "YmapEntityDiff",
      "YmapEntityFieldDiff",
      "AddedStreamFiles",
      "AddedStreamFile",
      "AddedStreamFileSource",
      "LeftOutAddition",
      "AddedItem",
      "OverwriteWarnings",
      "SourceUpdate",
      "SourceVersion",
      "SourceUpdateOutcome",
      "StreamFileOverwrite",
      "OverwriteFingerprint",
      "VanillaOverwrite",
      "YmapDiffSkip",
      "PipelineChanges",
      "PipelineReport",
      "CheckReport",
      "CheckIssue",
      "CheckIssueKind",
      "IgnoredOverwrite",
      "IgnoredOverwriteReason",
      "StoreChanges",
      "ReadResult",
      "ReadFileResult",
      "ReadOrigin",
      "YmapReadDocument",
      "YbnReadDocument",
      "CollisionFlags",
      "NamedFlags",
      "YbnReadPolygon",
      "ReadFingerprint",
      "Ymap",
    ] {
      assert!(actual.contains(&format!("export type {name} =")), "Missing {name}");
    }
    assert!(actual.contains("schemaVersion: number"));
    assert!(actual.contains("fileCount: number"));
    assert!(actual.contains("ymap: RTreeItem[]"));
    assert!(actual.contains("minX: number"));
    assert!(actual.contains("originalPath?: string"));
    assert!(
      actual
        .contains("{ Removed: { base_index: number; implied?: boolean; reason?: string | null } }")
    );
    assert!(actual.contains("{ Removed: { base_index: number; reason?: string | null } }"));
    assert!(actual.contains("anchor_base_index: number | null; target_index?: number | null"));
    assert!(!actual.contains("reason: string | null"));
    assert!(actual.contains("partner?: YmapComparisonPartner | null"));
    assert!(
      actual.contains("export type Change = \"Added\" | \"Modified\" | \"Replaced\" | \"Removed\"")
    );
    assert!(actual.contains("tolerance?: MatchTolerances"));
    assert!(actual.contains("source_conflicts?:"));
    assert!(actual.contains("modified_seconds: number"));
    assert!(actual.contains("entity_lod_parents: EntityLodParent[]"));
    assert!(actual.contains("export type EntityLodParentScope = \"self\" | \"parent\""));
    assert!(actual.contains("algorithm_versions?: { [key: string]: number }"));
    assert!(actual.contains("entities?: YmapEntityDiff[]"));
    assert!(actual.contains("ignore?: boolean; target?: OverwriteFingerprint | null"));
    assert!(actual.contains("skip?: YmapDiffSkip | null"));
    assert!(actual.contains("vanilla_cache: StoreChanges"));
    assert!(actual.contains("added: string[]"));
    assert!(!actual.contains(": bigint"));
    assert!(actual.contains("pairs: Partial<Record<ItemKind, number[][]>>"));
    // TypeScript rejects an index signature keyed by a union of string literals.
    for (offset, _) in actual.match_indices("[key: ") {
      let key = &actual[offset + "[key: ".len()..];
      assert!(key.starts_with("string]") || key.starts_with("number]"), "{}", &key[..40]);
    }
    fs::remove_file(path).unwrap();
  }

  #[test]
  fn stream_conflict_wire_names_remain_camel_case() {
    let report = StreamConflictReport {
      scanned_file_count: 2,
      conflict_count: 1,
      conflicts: BTreeMap::from([(
        ".ybn".into(),
        vec![StreamFileConflict {
          file_name: "collision.ybn".into(),
          paths: vec!["a/collision.ybn".into(), "b/collision.ybn".into()],
        }],
      )]),
    };
    let json = serde_json::to_value(report).unwrap();
    assert_eq!(json["scannedFileCount"], 2);
    assert_eq!(json["conflicts"][".ybn"][0]["fileName"], "collision.ybn");
    assert!(json.get("scanned_file_count").is_none());
  }
}
